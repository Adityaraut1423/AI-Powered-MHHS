    /**
     * Helper to parse raw string "Lat: 20.94527, Lon: 77.77428" -> "20.94527,77.77428"
     */
    private String extractCoordinates(String location) {
        if (location == null || location.isBlank()) {
            return "20.94522,77.77413";
        }

        Pattern pattern = Pattern.compile("[-+]?\\d*\\.\\d+|[-+]?\\d+");
        Matcher matcher = pattern.matcher(location);

        StringBuilder coords = new StringBuilder();
        while (matcher.find()) {
            if (coords.length() > 0) {
                coords.append(",");
            }
            coords.append(matcher.group());
        }

        return coords.length() > 0 ? coords.toString() : location.replaceAll("\\s+", "+");
    }
